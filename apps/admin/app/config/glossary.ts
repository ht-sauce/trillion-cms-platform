/**
 * 专有名词字典（**唯一事实来源**）
 *
 * 为什么要有这个文件：
 *   1) 后台里到处是「slug / canonical / 产物清单 / 内容指纹」这类专有名词，运营看不懂；
 *   2) 名词的中文叫法与解释以前散落在各页面里，改一处要全仓库找（且必然漏），口径慢慢就漂了。
 *
 * 用法（强制）：
 *   - 页面/组件里出现这些名词时，**不要就地硬编码中文**：
 *     取值用 `TERMS.<key>.label`，出问号说明用 `<TermHint term="<key>" />`
 *   - 新增名词只在本文件加一条，页面自动可用
 *   - `hint` 写给不懂技术的运营：它是什么、用在哪、改了会怎样，一到两句话说清
 */
export interface TermEntry {
  /** 名词的中文叫法（页面上显示的字） */
  label: string
  /** hover 问号时的说明 */
  hint: string
}

